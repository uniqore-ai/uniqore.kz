  var originalText = new WeakMap();
  var language = document.documentElement.dataset.language === 'kk' ? 'kk' : 'ru';

  function keyFor(value){
    return value.trim().replace(/\s+/g,' ');
  }

  function updateTextNode(node){
    if (!originalText.has(node)) originalText.set(node,node.nodeValue);
    var original = originalText.get(node);
    var key = keyFor(original);
    if (!key) return;
    var parent = node.parentElement;
    if (parent && /^(SCRIPT|STYLE)$/.test(parent.tagName)) return;
    if (language === 'ru') {
      node.nodeValue = original;
      return;
    }
    var translated = kk[key];
    if (!translated) return;
    var leading = (original.match(/^\s*/) || [''])[0];
    var trailing = (original.match(/\s*$/) || [''])[0];
    node.nodeValue = leading + translated + trailing;
  }

  function translateTree(root){
    if (root.nodeType === Node.TEXT_NODE) {
      updateTextNode(root);
      return;
    }
    var walker = document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
    var node;
    while ((node = walker.nextNode())) updateTextNode(node);
  }

  function setMeta(selector,value){
    var el = document.querySelector(selector);
    if (el) el.setAttribute('content',value);
  }

  function applyMetadata(){
    var page = location.pathname.indexOf('/crm') !== -1 ? 'crm' : 'home';
    var content = metadata[page][language];
    document.title = content.title;
    setMeta('meta[name="description"]',content.description);
    setMeta('meta[property="og:title"]',content.ogTitle);
    setMeta('meta[property="og:description"]',content.ogDescription);
    setMeta('meta[property="og:image:alt"]',content.ogTitle);
  }

  function updateMenu(){
    var names = language === 'kk'
      ? {long:'Қазақша',short:'ҚАЗ'}
      : {long:'Русский',short:'RU'};
    document.querySelectorAll('.language-current').forEach(function(el){ el.textContent = names.long; });
    document.querySelectorAll('.language-current-short').forEach(function(el){ el.textContent = names.short; });
    document.querySelectorAll('.language-menu summary').forEach(function(el){
      el.setAttribute('aria-label',language === 'kk' ? 'Тілді таңдау' : 'Выбрать язык');
    });
    document.querySelectorAll('[data-language-choice]').forEach(function(el){
      if (el.dataset.languageChoice === language) el.setAttribute('aria-current','true');
      else el.removeAttribute('aria-current');
    });
  }

  function persist(next){
    try { localStorage.setItem('uniqore-language',next); } catch (e) {}
  }

  function updateUrl(next){
    var url = new URL(location.href);
    if (next === 'kk') url.searchParams.set('lang','kk');
    else url.searchParams.delete('lang');
    history.replaceState(null,'',url.pathname + url.search + url.hash);
  }

  function setLanguage(next,save){
    if (next !== 'ru' && next !== 'kk') return;
    language = next;
    document.documentElement.lang = next;
    document.documentElement.dataset.language = next;
    if (save) {
      persist(next);
      updateUrl(next);
    }
    translateTree(document.body);
    applyMetadata();
    updateMenu();
    document.querySelectorAll('.language-menu[open]').forEach(function(el){ el.removeAttribute('open'); });
    document.documentElement.classList.add('i18n-ready');
  }

  document.querySelectorAll('[data-language-choice]').forEach(function(el){
    el.addEventListener('click',function(){
      setLanguage(el.dataset.languageChoice,true);
    });
  });

  document.addEventListener('click',function(event){
    document.querySelectorAll('.language-menu[open]').forEach(function(menu){
      if (!menu.contains(event.target)) menu.removeAttribute('open');
    });
  });
  document.addEventListener('keydown',function(event){
    if (event.key === 'Escape') {
      document.querySelectorAll('.language-menu[open]').forEach(function(menu){ menu.removeAttribute('open'); });
    }
  });

